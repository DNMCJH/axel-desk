'use strict';

const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { makeApp, requireWithStub } = require('./harness');
const stub = require('./obsidian_stub');
const { makePlugin } = require('../src/plugin');
require('../src/dom').setDocument(stub.__document);

async function main() {
  const vault = fs.mkdtempSync(path.join(os.tmpdir(), 'axel-desk-board-'));
  let plugin, view;
  try {
    fs.mkdirSync(path.join(vault, 'Notes'), { recursive: true });
    fs.mkdirSync(path.join(vault, '_history'), { recursive: true });
    fs.mkdirSync(path.join(vault, 'Templates'), { recursive: true });
    fs.writeFileSync(path.join(vault, 'Notes', '2026-10-09_long-full-name.md'), '- [ ] one\n- [ ] two\n- [x] done\n- [-] cancelled\n');
    fs.writeFileSync(path.join(vault, '_history', 'dated.md'), '- [ ] old 📅 2099-01-01\n');
    fs.writeFileSync(path.join(vault, 'Templates', 'example.md'), '- [ ] example\n');
    const old = path.join(vault, 'Notes', 'old.md');
    fs.writeFileSync(old, '- [ ] duplicate\n- [ ] duplicate\n');
    fs.utimesSync(old, new Date('2020-01-01'), new Date('2020-01-01'));
    const { app } = makeApp(vault, { maxDepth: 10 });
    let opened = null;
    app.workspace.getLeaf = () => ({ openFile: async (file) => { opened = file.path; }, view: null });
    const Plugin = process.argv.includes('--bundle')
      ? requireWithStub(path.join(__dirname, '..', 'main.js')) : makePlugin(stub);
    plugin = new Plugin(app, { id: 'axel-desk' });
    plugin._data = { autoOpen: false, cards: 'today', taskLimit: 1, taskPerSource: 1, taskMaxAgeDays: 45, taskExcludes: '' };
    await plugin.onload();
    view = plugin._views.get('desk-home')({ app });
    app.workspace.getLeavesOfType = (type) => type === 'desk-home' ? [{ view }] : [];
    stub.__document.body.appendChild(view.containerEl);
    await view.render();
    let rows = view.containerEl.querySelectorAll('.desk-task-file');
    assert.equal(rows.length, 1, 'shows a source-file summary rather than individual checkboxes');
    assert.match(rows[0].textContent, /2026-10-09_long-full-name\.md/, 'keeps the full filename and extension');
    assert.match(rows[0].textContent, /Notes\/2026-10-09_long-full-name\.md/, 'shows the full Vault-relative path');
    assert.match(rows[0].textContent, /2 项未完成/, 'counts all open boxes without a per-source cap');
    assert.doesNotMatch(view.containerEl.querySelector('.desk-card-today').textContent, /我的|等人|进行中/, 'removes inferred ownership/status tabs');
    assert.doesNotMatch(view.containerEl.textContent, /dated.md|example.md/, 'excludes historical and template files even with due dates');
    view.taskFilesLimit = 20;
    await view.rerender();
    assert.match(view.containerEl.querySelector('.desk-task-files').textContent, /old.md/, 'does not hide old files by the task-age cutoff');
    assert.equal(view.containerEl.querySelectorAll('.desk-task-file').length, 2);
    rows = view.containerEl.querySelectorAll('.desk-task-file');
    rows[0].querySelector('.desk-row-main').click();
    await new Promise((resolve) => setTimeout(resolve, 0));
    assert.equal(opened, 'Notes/2026-10-09_long-full-name.md');
    const source = fs.readFileSync(path.join(vault, opened), 'utf8');
    rows = view.containerEl.querySelectorAll('.desk-task-file');
    rows[0].querySelector('.desk-row-toggle').click();
    await new Promise((resolve) => setTimeout(resolve, 30));
    assert.equal(view.containerEl.querySelectorAll('.desk-task-file').length, 1, 'file can be removed independently');
    assert.equal(fs.readFileSync(path.join(vault, opened), 'utf8'), source, 'removal never edits the note');
    const key = Object.keys(plugin.settings.itemStates).find((k) => k.startsWith('task-files:'));
    assert.ok(key, 'file removal uses the existing recoverable item-state store');
    const changedFile = app.vault.getAbstractFileByPath(opened);
    await app.vault.modify(changedFile, source + '- [ ] added later\n');
    await view.refresh();
    assert.equal(view.containerEl.querySelectorAll('.desk-task-file').length, 1, 'removed file stays removed after source edits');
    const hiddenRestart = new Plugin(app, { id: 'axel-desk' });
    hiddenRestart._data = JSON.parse(JSON.stringify(plugin._data));
    await hiddenRestart.loadSettings();
    const hiddenView = new (view.constructor)({ app }, hiddenRestart);
    await hiddenView.render();
    assert.equal(hiddenView.containerEl.querySelectorAll('.desk-task-file').length, 1, 'removed file stays removed after plugin restart');
    await hiddenView.onClose();
    await view.restoreItem(key);
    assert.equal(view.containerEl.querySelectorAll('.desk-task-file').length, 2, 'restoration returns the file');
    assert.match(view.containerEl.querySelector('.desk-task-file').textContent, /3 项未完成/);
    await view.addManualTask('  Review cancellation  ');
    assert.equal(plugin.settings.manualTasks[0].text, 'Review cancellation');
    const id = plugin.settings.manualTasks[0].id;
    assert.ok(id);
    const beforeAdd = plugin.settings.manualTasks.length;
    await view.addManualTask('   ');
    assert.equal(plugin.settings.manualTasks.length, beforeAdd, 'blank entries are rejected');
    await view.editManualTask(id, 'Review cancellation in the worker');
    assert.equal(plugin.settings.manualTasks[0].text, 'Review cancellation in the worker');
    await view.toggleManualTask(id);
    assert.equal(plugin.settings.manualTasks[0].done, true, 'completes a personal task');
    assert.match(view.containerEl.textContent, /已完成/);
    await view.toggleManualTask(id);
    assert.equal(plugin.settings.manualTasks[0].done, false, 'can reopen a personal task');
    assert.equal(fs.readFileSync(path.join(vault, opened), 'utf8'), source + '- [ ] added later\n', 'personal tasks never modify source notes');
    const manualRow = view.containerEl.querySelector('.desk-manual-task');
    manualRow.querySelector('.desk-manual-remove').click();
    await new Promise((resolve) => setTimeout(resolve, 30));
    assert.equal(view.containerEl.querySelectorAll('.desk-manual-task').length, 0, 'can remove a personal task');
    const manualKey = Object.keys(plugin.settings.itemStates).find((k) => k.startsWith('manual-tasks:'));
    assert.ok(manualKey);
    await view.restoreItem(manualKey);
    assert.equal(view.containerEl.querySelectorAll('.desk-manual-task').length, 1);
    const saved = JSON.parse(JSON.stringify(plugin._data));
    const restarted = new Plugin(app, { id: 'axel-desk' });
    restarted._data = saved;
    await restarted.loadSettings();
    assert.equal(restarted.settings.manualTasks[0].id, id, 'manual tasks persist across restart');
    const originalSave = plugin.saveData.bind(plugin);
    plugin.saveData = async () => { throw new Error('disk unavailable'); };
    const beforeFailedSave = JSON.stringify(plugin.settings.manualTasks);
    const beforeFailedRemoval = JSON.stringify(plugin.settings.itemStates);
    const removalResult = await view.closeItem({ cardId: 'task-files', id: opened, label: opened, signature: opened, sourcePaths: [opened] });
    assert.equal(removalResult, false, 'failed removal reports failure rather than pretending persistence');
    assert.equal(JSON.stringify(plugin.settings.itemStates), beforeFailedRemoval, 'failed removal rolls back display state');
    await view.addManualTask('must not pretend to save');
    assert.equal(JSON.stringify(plugin.settings.manualTasks), beforeFailedSave, 'failed saves roll back the in-memory mutation');
    plugin.saveData = originalSave;
    const input = view.containerEl.querySelector('.desk-manual-input');
    input.focus();
    input.value = 'Unsent thought';
    input.dispatchEvent(new stub.__window.Event('input'));
    input.dispatchEvent(new stub.__window.Event('compositionstart'));
    input.closest('form').dispatchEvent(new stub.__window.Event('submit', { cancelable: true }));
    assert.equal(plugin.settings.manualTasks.length, beforeAdd, 'IME confirmation does not submit a new task');
    input.dispatchEvent(new stub.__window.Event('compositionend'));
    await view.rerender();
    assert.equal(stub.__document.activeElement, input, 'background rerender cannot remove the focused editor');
    assert.equal(input.isConnected, true);
    input.blur();
    await new Promise((resolve) => setTimeout(resolve, 30));
    assert.equal(view.containerEl.querySelector('.desk-manual-input').value, 'Unsent thought', 'preserves unsent draft after deferred render');
    plugin.settings.cards = 'today, scratch';
    await view.rerender();
    const scratch = view.containerEl.querySelector('.desk-scratch');
    scratch.focus();
    scratch.value = 'Thinking slowly';
    scratch.dispatchEvent(new stub.__window.Event('input'));
    const originalInterval = window.setInterval;
    let galleryTick = null;
    window.setInterval = (fn) => { galleryTick = fn; return 0; };
    view.configureGalleryRotation(18, 6);
    window.setInterval = originalInterval;
    galleryTick();
    await new Promise((resolve) => setTimeout(resolve, 20));
    await view.rerender();
    assert.equal(stub.__document.activeElement, scratch, 'the same editor guard protects the existing scratchpad during gallery rotation');
    scratch.blur();
    await new Promise((resolve) => setTimeout(resolve, 30));
    assert.equal(plugin.settings.scratchText, 'Thinking slowly');
    console.log('task board: source grouping/removal/restoration, personal tasks, persistence, save failure and focused-editor regression passed');
  } finally {
    if (view) { await view.onClose(); view.containerEl.remove(); }
    if (plugin) plugin.onunload();
    fs.rmSync(vault, { recursive: true, force: true });
  }
}
main().catch((error) => { console.error(error.stack); process.exitCode = 1; });
